/*
 * Problem: #50 Pow(x, n)
 * Platform: LeetCode
 * Link: https://leetcode.com/problems/powx-n/
 * Approach: Used the built-in pow() function to calculate the power.
 * Time Complexity: O(1) (built-in) | Space Complexity: O(1)
 */

class Solution {
public:
    double myPow(double x, int n) {
        return pow(x,n);
    }
};